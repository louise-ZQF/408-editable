import { test, expect } from '@playwright/test'

test('教材新增、改名、刷新持久保存、删除和回收站恢复', async ({ page }) => {
  await page.goto('/#/')
  await page.getByRole('button', { name: '内容管理', exact: true }).click()
  await page.getByRole('button', { name: '＋ 新增书籍', exact: true }).click()
  await page.getByLabel('标题', { exact: true }).fill('端到端测试教材')
  await page.getByRole('button', { name: '保存书籍信息', exact: true }).click()
  await expect(page.getByRole('heading', { name: '端到端测试教材', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '内容管理', exact: true }).click()
  await page.getByRole('button', { name: '端到端测试教材', exact: true }).click()
  await expect(page.getByLabel('标题', { exact: true })).toHaveValue('端到端测试教材')
  await page.getByRole('button', { name: '删除书籍', exact: true }).click()
  await page.getByRole('button', { name: '确认', exact: true }).click()
  await page.getByRole('button', { name: /^回收站/ }).click()
  await expect(page.getByRole('heading', { name: '端到端测试教材', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '恢复内容', exact: true }).click()
  await expect(page.getByText('回收站是空的。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '教材与知识', exact: true }).click()
  await expect(page.getByRole('button', { name: '端到端测试教材', exact: true })).toBeVisible()
})

test('正文修改在刷新后保留，并参与搜索', async ({ page }) => {
  await page.goto('/#/knowledge/data-structures/ds-section-5')
  await page.getByRole('button', { name: '内容管理', exact: true }).click()
  await page.locator('.ed-child').filter({ hasText: '树的基本概念' }).click()
  const text = page.getByLabel('正文（支持 Markdown、代码和 $LaTeX$）', { exact: true }).first()
  await text.fill('**自定义学习标记**：这段内容来自个人编辑器。')
  await page.getByRole('button', { name: '保存正文', exact: true }).click()
  await page.getByRole('button', { name: '关闭内容管理', exact: true }).click()
  await expect(page.locator('[data-testid="knowledge-article-column"]')).toContainText('自定义学习标记')
  await page.reload()
  await expect(page.locator('[data-testid="knowledge-article-column"]')).toContainText('自定义学习标记')
  await page.goto('/#/search?q=自定义学习标记')
  await expect(page.locator('.result-item').first()).toBeVisible({ timeout: 30000 })
  await expect(page.locator('.result-item').first()).toContainText('自定义学习标记')
})

test('移动端管理界面没有横向溢出且能关闭', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/')
  await page.getByRole('button', { name: '内容管理', exact: true }).click()
  await expect(page.getByRole('heading', { name: '我的教材工作台', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '网站设置', exact: true }).click()
  const dimensions = await page.locator('.ed-shell').evaluate(el => ({ width: el.clientWidth, scrollWidth: el.scrollWidth }))
  expect(dimensions.scrollWidth).toBeLessThanOrEqual(dimensions.width)
  await page.getByRole('button', { name: '关闭内容管理', exact: true }).click()
  await expect(page.locator('.ed-shell')).toHaveCount(0)
})
